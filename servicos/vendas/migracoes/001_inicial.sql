-- Banco sqldb-vendas (Microsserviço de Vendas)
CREATE TABLE OPORTUNIDADE (
  id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
  cliente_id UNIQUEIDENTIFIER NOT NULL,
  vendedor_id UNIQUEIDENTIFIER NOT NULL,
  titulo NVARCHAR(120) NOT NULL,
  valor_estimado DECIMAL(12, 2) NOT NULL CHECK (valor_estimado >= 0),
  data_prevista DATE NOT NULL,
  etapa VARCHAR(20) NOT NULL
    CHECK (etapa IN ('PROSPECCAO', 'CONTATO', 'PROPOSTA', 'FECHADO_GANHO', 'FECHADO_PERDIDO')),
  motivo_perda VARCHAR(20) NULL
    CHECK (motivo_perda IN ('PRECO', 'CONCORRENTE', 'SEM_VERBA', 'SEM_RESPOSTA')),
  fechada_em DATETIME2 NULL,
  criada_em DATETIME2 NOT NULL,
  versao INT NOT NULL,
  -- RF29: motivo obrigatório somente quando perdida
  CONSTRAINT CK_OPORTUNIDADE_MOTIVO CHECK (
    (etapa = 'FECHADO_PERDIDO' AND motivo_perda IS NOT NULL) OR (etapa <> 'FECHADO_PERDIDO' AND motivo_perda IS NULL)
  )
);
CREATE INDEX IX_OPORTUNIDADE_VENDEDOR_ETAPA ON OPORTUNIDADE (vendedor_id, etapa);
CREATE INDEX IX_OPORTUNIDADE_CLIENTE ON OPORTUNIDADE (cliente_id);

CREATE TABLE HISTORICO_ETAPA (
  id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
  oportunidade_id UNIQUEIDENTIFIER NOT NULL REFERENCES OPORTUNIDADE (id),
  etapa_origem VARCHAR(20) NULL,
  etapa_destino VARCHAR(20) NOT NULL,
  usuario_id UNIQUEIDENTIFIER NOT NULL,
  ocorrido_em DATETIME2 NOT NULL
);

CREATE TABLE CLIENTE_RESUMO (
  cliente_id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
  nome NVARCHAR(120) NOT NULL,
  empresa NVARCHAR(120) NOT NULL,
  vendedor_id UNIQUEIDENTIFIER NOT NULL,
  excluido BIT NOT NULL,
  versao INT NOT NULL
);

CREATE TABLE EQUIPE_PROJECAO (
  usuario_id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
  nome NVARCHAR(120) NOT NULL,
  perfil VARCHAR(20) NOT NULL,
  gerente_id UNIQUEIDENTIFIER NULL,
  ativo BIT NOT NULL
);
CREATE INDEX IX_EQUIPE_GERENTE ON EQUIPE_PROJECAO (gerente_id);

CREATE TABLE OUTBOX (
  id UNIQUEIDENTIFIER NOT NULL PRIMARY KEY,
  tipo NVARCHAR(200) NOT NULL,
  assunto NVARCHAR(200) NOT NULL,
  versao INT NOT NULL,
  ocorrido_em DATETIME2 NOT NULL,
  payload NVARCHAR(MAX) NOT NULL,
  publicado_em DATETIME2 NULL
);

CREATE TABLE EVENTO_PROCESSADO (
  evento_id NVARCHAR(80) NOT NULL PRIMARY KEY,
  tipo NVARCHAR(200) NOT NULL,
  processado_em DATETIME2 NOT NULL
);
